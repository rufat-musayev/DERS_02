-- TASK 1
SELECT 
    FIRST_NAME,
    LAST_NAME,
    SALARY,
    CASE 
        WHEN SALARY < 6000 THEN 'ASAGI'
        WHEN SALARY > 12000 THEN 'YUKSEK'
        ELSE 'ORTA'
    END AS SALARY_LEVEL
FROM HR.EMPLOYEES;

-- TASK 2
SELECT 
    FIRST_NAME,
    JOB_ID,
    CASE JOB_ID
        WHEN 'IT_PROG' THEN 'Proqramci'
        WHEN 'SA_REP' THEN 'Satis numayendesi'
        WHEN 'ST_CLERK' THEN 'Anbar iscisi'
        ELSE 'Diger'
    END AS VEZIFE
FROM HR.EMPLOYEES;

-- TASK 3
SELECT 
    FIRST_NAME,
    COMMISSION_PCT,
    CASE 
        WHEN COMMISSION_PCT IS NULL THEN 'Komissiya yoxdur'
        ELSE 'Komissiya var'
    END AS KOMISSIYA_STATUSU
FROM HR.EMPLOYEES;

-- TASK 4
SELECT 
    CITY,
    COUNTRY_ID,
    CASE
        WHEN COUNTRY_ID IN ('US', 'CA', 'MX', 'BR') THEN 'Amerika'
        WHEN COUNTRY_ID IN ('UK', 'DE', 'IT', 'NL', 'CH') THEN 'Avropa'
        WHEN COUNTRY_ID IN ('JP', 'CN', 'IN', 'SG') THEN 'Asiya'
        ELSE 'Diger'
    END AS QITE
FROM HR.LOCATIONS;

-- TASK 5
SELECT 
    FIRST_NAME,
    DEPARTMENT_ID,
    SALARY,
    CASE 
        WHEN DEPARTMENT_ID = 80 THEN SALARY * 0.10
        WHEN DEPARTMENT_ID = 60 THEN SALARY * 0.15
        ELSE SALARY * 0.05
    END AS BONUS
FROM HR.EMPLOYEES
ORDER BY BONUS DESC;

-- TASK 6
SELECT 
       FIRST_NAME, 
       SALARY,
       CASE
           WHEN SALARY > 15000 THEN 'Yuksek' 
           WHEN SALARY > 5000  THEN 'Orta'
           ELSE 'Asagi'
       END AS "Seviyye"
FROM HR.EMPLOYEES;
-- ELSE hissesinde 'Asagi' yazilmalidir 0 yerine
-- Ilk novbede daha boyug olan sert yazilmalidir sertler duzgun ardicillig ile olsun deye
-- END AS hissesi qosa dirnag ile yazilmalidir

-- TASK 7
SELECT 
    FIRST_NAME,
    JOB_ID,
    MANAGER_ID,
    CASE 
        WHEN MANAGER_ID IS NULL THEN 'DirekTor'
        WHEN MANAGER_ID = 100 THEN 'Direktorun komandasi'
        WHEN UPPER(JOB_ID) LIKE '%MAN' OR UPPER(JOB_ID) LIKE '%MGR' THEN 'Menecer'
        ELSE 'Isci'
    END AS ROL
FROM HR.EMPLOYEES;

-- TASK 8
SELECT 
    FIRST_NAME,
    SALARY,
    COMMISSION_PCT,
    NVL(SALARY * COMMISSION_PCT * 12, 0) AS ILLIK_KOMISSIYA,
    (SALARY * 12) + NVL(SALARY * COMMISSION_PCT * 12, 0) AS ILLIK_GELIR
FROM HR.EMPLOYEES
ORDER BY ILLIK_GELIR DESC;

-- TASK 9
SELECT 
    E.FIRST_NAME,
    J.JOB_TITLE,
    E.SALARY,
    J.MIN_SALARY,
    J.MAX_SALARY,
    CASE 
        WHEN E.SALARY = J.MIN_SALARY THEN 'Minimumda'
        WHEN E.SALARY = J.MAX_SALARY THEN 'Maksimumda'
        WHEN E.SALARY < (J.MIN_SALARY+J.MAX_SALARY)/2 THEN 'Asagi yarida'
        ELSE 'Yuxari yarida'
    END AS MOVGE    
FROM HR.EMPLOYEES E
JOIN HR.JOBS J 
    ON E.JOB_ID = J.JOB_ID;

-- TASK 10
SELECT 
    E.FIRST_NAME,
    E.LAST_NAME,
    NVL(D.DEPARTMENT_NAME, 'Sobesiz') AS SOBE
    -- QARANLIG QALDI CASE HISSESI NECE OLMALIDIRSA
FROM HR.EMPLOYEES E
LEFT JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN HR.LOCATIONS L
    ON D.LOCATION_ID = L.LOCATION_ID;

