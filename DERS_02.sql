-- TASK 1
SELECT 
    MANAGER_ID,
    COUNT(FIRST_NAME) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY MANAGER_ID
ORDER BY COUNT(FIRST_NAME) DESC;

-- TASK 2
SELECT 
    COUNTRY_ID,
    COUNT(LOCATION_ID) AS OFIS_SAYI
FROM HR.LOCATIONS
GROUP BY COUNTRY_ID
ORDER BY COUNT(LOCATION_ID) DESC;

-- TASK 3
SELECT  
    E.FIRST_NAME,
    E.LAST_NAME,
    D.JOB_TITLE
FROM HR.EMPLOYEES E
JOIN HR.JOBS D
    ON E.JOB_ID = D.JOB_ID;

-- TASK 4
SELECT
    DEPARTMENT_ID,
    ROUND(AVG(SALARY),2) AS ORTA_MASS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 8000;

-- TASK 5
SELECT 
    DEPARTMENT_ID,
    COUNT(CASE WHEN SALARY > 3000 THEN 1 END) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING COUNT(CASE WHEN SALARY > 3000 THEN 1 END) > 3;

-- TASK 6
SELECT 
    E.JOB_TITLE,
    COUNT(D.EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.JOBS E
LEFT JOIN HR.EMPLOYEES D 
    ON E.JOB_ID = D.JOB_ID
GROUP BY E.JOB_TITLE;

-- TASK 7
SELECT
    D.CITY,
    D.COUNTRY_ID
FROM  HR.DEPARTMENTS E
RIGHT JOIN HR.LOCATIONS D
    ON E.LOCATION_ID = D.LOCATION_ID
WHERE E.DEPARTMENT_ID IS NULL;

-- TASK 8
SELECT 
    J.JOB_TITLE,  
    AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J 
    ON E.JOB_ID = J.JOB_ID
HAVING AVG(E.SALARY) > 10000
GROUP BY J.JOB_TITLE;
-- WITH AGGREGATE FUNCTIONS WE USE HAVING
-- WE SHOULD USE J.JOB_ID FOR ON IN JOIN FUNCTION
-- WE DELETE LAST_NAME WE DONT NEED IT 

-- TASK 9
SELECT
    L.CITY,
    COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI,
    AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L
    ON L.LOCATION_ID = D.LOCATION_ID
GROUP BY L.CITY
HAVING COUNT(E.EMPLOYEE_ID) > 5
ORDER BY AVG(E.SALARY) DESC;
 
-- TASK 10
SELECT 
    D.DEPARTMENT_NAME,
    COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E
    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
ORDER BY ISCI_SAYI DESC, D.DEPARTMENT_NAME ASC
GROUP BY D.DEPARTMENT_NAME;